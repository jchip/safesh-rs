/// Paths that are never readable.
pub const SENSITIVE_READ_PATHS: &[&str] = &[
    "${HOME}/.ssh",
    "${HOME}/.gnupg",
    "${HOME}/.gpg",
    "${HOME}/.aws/credentials",
    "${HOME}/.config/gh",
    "${HOME}/.netrc",
    "${HOME}/.npmrc",
    "${HOME}/.pypirc",
    "${HOME}/.docker/config.json",
    "${HOME}/.kube/config",
];

/// Paths that are never writable.
pub const SENSITIVE_WRITE_PATHS: &[&str] = &[
    "${HOME}/.ssh",
    "${HOME}/.gnupg",
    "${HOME}/.gpg",
    "${HOME}/.aws",
    "${HOME}/.config/gh",
    "${HOME}/.netrc",
    "${HOME}/.npmrc",
    "${HOME}/.pypirc",
    "${HOME}/.docker/config.json",
    "${HOME}/.kube/config",
    "${HOME}/.bashrc",
    "${HOME}/.bash_profile",
    "${HOME}/.zshrc",
    "${HOME}/.profile",
];

fn strings(items: &[&str]) -> Vec<String> {
    items.iter().map(|s| (*s).to_string()).collect()
}

/// Built-in config. Static lists only.
#[must_use]
pub fn default_config() -> Config {
    Config {
        permissions: Some(PermissionsConfig {
            read: Some(strings(&["${CWD}", "${HOME}", "/tmp", "${HOME}/.claude"])),
            deny_read: Some(strings(SENSITIVE_READ_PATHS)),
            write: Some(strings(&["/tmp", "/dev/null", "${HOME}/.claude"])),
            deny_write: Some(strings(SENSITIVE_WRITE_PATHS)),
            net: Some(NetPermission::Hosts(Vec::new())),
            run: Some(strings(SAFE_COMMANDS)),
            env: Some(strings(&["HOME", "PATH", "TERM", "USER", "LANG"])),
        }),
        env: Some(EnvConfig {
            allow: Some(strings(&[
                "HOME", "PATH", "TERM", "EDITOR", "SHELL", "USER", "LANG",
            ])),
            mask: Some(strings(&[
                "*_KEY",
                "*_SECRET",
                "*_TOKEN",
                "*_PASSWORD",
                "AWS_*",
                "GITHUB_TOKEN",
            ])),
            allow_read_all: None,
        }),
        timeout: Some(DEFAULT_TIMEOUT_MS),
        passthrough_analyzable: Some(true),
        ..Config::default()
    }
}
